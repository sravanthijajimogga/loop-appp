export type LocationOption = {
  kind: "city" | "country";
  label: string;
  value: string;
  city: string;
  country: string;
  isoCode: string;
};

export function locationOptionsFromCountries(
  countries: Array<{
    isoCode: string;
    name: string;
    capital: string | null;
    cities: Array<{ name: string }>;
  }>,
): LocationOption[] {
  const options: LocationOption[] = [];
  for (const country of countries) {
    options.push({
      kind: "country",
      label: country.name,
      value: country.name,
      city: country.capital ?? country.name,
      country: country.name,
      isoCode: country.isoCode,
    });
    for (const city of country.cities) {
      options.push({
        kind: "city",
        label: `${city.name}, ${country.name}`,
        value: city.name,
        city: city.name,
        country: country.name,
        isoCode: country.isoCode,
      });
    }
  }
  return options.sort((a, b) => a.label.localeCompare(b.label));
}
